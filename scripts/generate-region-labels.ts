/**
 * Regenerate lib/zh/region-labels.generated.ts from PROVINCES + OpenCC cn→tw.
 * Run: npx tsx scripts/generate-region-labels.ts
 */
import { writeFileSync } from 'node:fs';
import { Converter } from 'opencc-js';
import { PROVINCES } from '../lib/ziwei/cities';

const cn2tw = Converter({ from: 'cn', to: 'tw' });

const names = new Set<string>();
for (const p of PROVINCES) {
  names.add(p.name);
  for (const c of p.cities) names.add(c.name);
}

const sorted = [...names].sort((a, b) => a.localeCompare(b, 'zh-Hans'));

const esc = (s: string) => s.replace(/\\/g, '\\\\').replace(/'/g, "\\'");

let out = '/** Auto-generated by scripts/generate-region-labels.ts — do not edit. */\n';
out += 'export const REGION_DISPLAY_LABEL: Readonly<Record<string, string>> = {\n';
for (const cn of sorted) {
  const tw = cn2tw(cn);
  out += `  '${esc(cn)}': '${esc(tw)}',\n`;
}
out += '};\n';

writeFileSync('lib/zh/region-labels.generated.ts', out);
console.log(`Wrote ${sorted.length} region display labels.`);
